const extractJsonObject = (text) => {
    if (!text || typeof text !== "string") {
        return null;
    }

    const start = text.indexOf("{");

    if (start === -1) {
        return null;
    }

    let depth = 0;
    let inString = false;
    let escaped = false;

    for (let i = start; i < text.length; i++) {
        const char = text[i];

        if (escaped) {
            escaped = false;
            continue;
        }

        if (char === "\\") {
            escaped = true;
            continue;
        }

        if (char === '"') {
            inString = !inString;
            continue;
        }

        if (inString) {
            continue;
        }

        if (char === "{") {
            depth++;
        } else if (char === "}") {
            depth--;

            if (depth === 0) {
                return text.substring(start, i + 1);
            }
        }
    }

    return null;
};

const parseAIResponse = (response) => {

    console.log(
        "🔍 Parsing AI response:",
        response?.substring(0, 500)
    );

    if (!response) {
        return {
            actions: [],
            response: ""
        };
    }

    // ---------------------------------------------------------
    // NEW FORMAT
    //
    // {
    //   "actions": [
    //      {
    //        "function": "createProject",
    //        "arguments": {}
    //      }
    //   ]
    // }
    // ---------------------------------------------------------

    const jsonText = extractJsonObject(response);

    if (jsonText) {

        try {

            const parsed = JSON.parse(jsonText);

            if (Array.isArray(parsed.actions)) {

                const actions = parsed.actions
                    .filter(action =>
                        action &&
                        typeof action.function === "string"
                    )
                    .map(action => ({
                        function: action.function.trim(),
                        arguments:
                            action.arguments &&
                                typeof action.arguments === "object"
                                ? action.arguments
                                : {}
                    }));

                console.log(
                    `✅ Parsed ${actions.length} AI action(s)`
                );

                return {
                    actions,
                    response: ""
                };
            }

        } catch (error) {

            console.error(
                "❌ Failed to parse JSON action plan:",
                error
            );
        }
    }


    // ---------------------------------------------------------
    // BACKWARD COMPATIBILITY
    //
    // Supports:
    //
    // [FUNCTION:createProject]{...}
    // [FUNCTION:createProject]{...}
    //
    // ---------------------------------------------------------

    const actions = [];

    const functionRegex =
        /\[FUNCTION:(\w+)\]\s*(\{(?:[^{}]|"(?:\\.|[^"\\])*")*\})/g;

    let match;

    while ((match = functionRegex.exec(response)) !== null) {

        try {

            actions.push({
                function: match[1],
                arguments: JSON.parse(match[2])
            });

        } catch (error) {

            console.error(
                "❌ Failed to parse legacy function:",
                match[0]
            );
        }
    }

    if (actions.length > 0) {

        console.log(
            `✅ Parsed ${actions.length} legacy action(s)`
        );

        return {
            actions,
            response: response
                .replace(functionRegex, "")
                .trim()
        };
    }


    console.log("ℹ️ No function/action detected");

    return {
        actions: [],
        response
    };
};

const buildActionMessage = (item) => {

    const functionName = item.function;
    const result = item.result || {};
    const params = item.arguments || {};


    // ---------------------------------------------------------
    // PERMISSION DENIED
    // ---------------------------------------------------------

    if (item.permissionDenied) {
        return `❌ ${item.error}`;
    }


    // ---------------------------------------------------------
    // FAILED
    // ---------------------------------------------------------

    if (!item.success) {

        const error =
            result?.error ||
            result?.message ||
            item.error ||
            "The operation could not be completed.";

        return `❌ ${error}`;
    }


    // ---------------------------------------------------------
    // CREATE PROJECT
    // ---------------------------------------------------------

    if (functionName === "createProject") {

        const projectName =
            result?.project?.name ||
            result?.name ||
            params.name ||
            "the project";

        return `✅ Project "${projectName}" was created successfully.`;
    }


    // ---------------------------------------------------------
    // CREATE TASK
    // ---------------------------------------------------------

    if (functionName === "createTask") {

        const taskName =
            result?.task?.name ||
            result?.name ||
            params.name ||
            "the task";

        const projectName =
            result?.task?.projectName ||
            result?.projectName ||
            params.projectName;

        if (projectName) {

            return (
                `✅ Task "${taskName}" was created successfully ` +
                `under project "${projectName}".`
            );
        }

        return (
            `✅ Task "${taskName}" was created successfully.`
        );
    }


    // ---------------------------------------------------------
    // ASSIGN PROJECT
    // ---------------------------------------------------------

    if (functionName === "assignProject") {

        const projectName =
            result?.projectName ||
            params.projectName ||
            "the project";

        const managerName =
            result?.managerName ||
            params.managerName ||
            "the Project Manager";

        return (
            `✅ Project "${projectName}" was successfully ` +
            `assigned to Project Manager "${managerName}".`
        );
    }


    // ---------------------------------------------------------
    // ASSIGN TASK
    // ---------------------------------------------------------

    if (functionName === "assignTask") {

        const taskName =
            result?.taskName ||
            params.taskName ||
            "the task";

        const assigneeName =
            result?.assigneeName ||
            params.assigneeName ||
            "the Member";

        return (
            `✅ Task "${taskName}" was successfully ` +
            `assigned to Member "${assigneeName}".`
        );
    }


    // ---------------------------------------------------------
    // UPDATE TASK STATUS
    // ---------------------------------------------------------

    if (functionName === "updateTaskStatus") {

        const taskName =
            result?.taskName ||
            params.taskName ||
            params.taskId ||
            "the task";

        const status =
            result?.status ||
            params.status ||
            "the requested status";

        return (
            `✅ Task "${taskName}" status was successfully ` +
            `updated to "${status}".`
        );
    }


    // ---------------------------------------------------------
    // DELETE TASK
    // ---------------------------------------------------------

    if (functionName === "deleteTask") {

        const taskName =
            result?.taskName ||
            params.taskName ||
            params.taskId ||
            "the task";

        return (
            `✅ Task "${taskName}" was successfully deleted.`
        );
    }


    // ---------------------------------------------------------
    // SUBMIT WORK
    // ---------------------------------------------------------

    if (functionName === "submitWork") {

        const taskName =
            result?.taskName ||
            params.taskName ||
            params.taskId ||
            "the task";

        return (
            `✅ Your work submission for "${taskName}" ` +
            `was submitted successfully.`
        );
    }


    // ---------------------------------------------------------
    // FALLBACK
    // ---------------------------------------------------------

    return "✅ The requested operation was completed successfully.";
};

const generateMultiActionResponse = async (
    results,
    user
) => {

    if (!results || results.length === 0) {
        return "I couldn't identify an operation to perform.";
    }


    const messages =
        results.map(buildActionMessage);


    // ---------------------------------------------------------
    // SINGLE ACTION
    // ---------------------------------------------------------

    if (messages.length === 1) {
        return messages[0];
    }


    // ---------------------------------------------------------
    // MULTIPLE ACTIONS
    // ---------------------------------------------------------

    const successful =
        results.filter(
            item => item.success
        ).length;

    const failed =
        results.length - successful;


    let response =
        `I processed ${results.length} requested operations.\n\n`;


    messages.forEach(
        (message, index) => {

            response +=
                `${index + 1}. ${message}\n`;

        }
    );


    if (failed === 0) {

        response +=
            `\n✅ All ${successful} operations were completed successfully.`;

    } else if (successful > 0) {

        response +=
            `\n⚠️ ${successful} operation(s) succeeded and ` +
            `${failed} operation(s) could not be completed.`;

    } else {

        response +=
            `\n❌ None of the requested operations were completed.`;
    }


    return response.trim();
};

